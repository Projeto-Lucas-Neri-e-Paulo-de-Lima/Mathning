function finishPalette(base: typeof LIGHT_BASE | typeof DARK_BASE, mode: ResolvedThemeMode): ColorTokens {
  const isLight = mode === "light";
  return {
    ...base,
    cardBorder: isLight ? "rgba(92, 73, 245, 0.1)" : "rgba(123, 108, 248, 0.18)",
    overlayPurple: isLight ? "rgba(92, 73, 245, 0.14)" : "rgba(123, 108, 248, 0.2)",
    accentBlob: isLight ? "rgba(92, 73, 245, 0.09)" : "rgba(123, 108, 248, 0.18)",
    accentBlobSoft: isLight ? "rgba(123, 108, 248, 0.06)" : "rgba(155, 140, 255, 0.13)",
    heroBlob: "rgba(255, 255, 255, 0.1)",
    heroBlobSmall: "rgba(255, 255, 255, 0.08)",
  };
}

export function getThemeColors(mode: ResolvedThemeMode): ColorTokens {
  const base = mode === "light" ? LIGHT_BASE : DARK_BASE;
  return finishPalette(base, mode);
}
